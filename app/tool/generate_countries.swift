// Generates lib/core/i18n/countries.g.dart — every ISO 3166-1 alpha-2 country
// with its English and Arabic name and its CLDR default currency.
//
// Sources (both maintained upstream, neither hand-typed here):
//   - codes: the IANA tz database's `iso3166.tab` (ISO 3166-1 alpha-2, public
//     domain), shipped with macOS at /usr/share/zoneinfo/iso3166.tab;
//   - names and default currency: Unicode CLDR, through Foundation's Locale.
//
// Run from app/:
//   swift tool/generate_countries.swift [/path/to/iso3166.tab] > lib/core/i18n/countries.g.dart
// then `dart format lib/core/i18n/countries.g.dart`.
import Foundation

let path = CommandLine.arguments.count > 1
  ? CommandLine.arguments[1] : "/usr/share/zoneinfo/iso3166.tab"
let table = try String(contentsOfFile: path, encoding: .utf8)
let codes = table.split(separator: "\n")
  .filter { !$0.hasPrefix("#") && !$0.isEmpty }
  .map { String($0.split(separator: "\t")[0]) }

let en = Locale(identifier: "en")
let ar = Locale(identifier: "ar")

func dartString(_ s: String) -> String {
  "'" + s.replacingOccurrences(of: "\\", with: "\\\\")
    .replacingOccurrences(of: "'", with: "\\'")
    .replacingOccurrences(of: "$", with: "\\$") + "'"
}

var out = """
// GENERATED by tool/generate_countries.swift — do not edit by hand.
// Codes: IANA tz iso3166.tab (ISO 3166-1 alpha-2). Names and default
// currency: Unicode CLDR via Foundation.
// \(codes.count) countries.

part of 'country_catalog.dart';

const List<IsoCountry> _isoCountries = <IsoCountry>[

"""
for code in codes {
  guard let nameEn = en.localizedString(forRegionCode: code),
        let nameAr = ar.localizedString(forRegionCode: code) else {
    FileHandle.standardError.write("no CLDR name for \(code)\n".data(using: .utf8)!)
    exit(1)
  }
  // CLDR uses XXX ("no currency") for uninhabited territories.
  let cldrCurrency = Locale(identifier: "en_\(code)").currency?.identifier
  let currency = cldrCurrency == "XXX" ? nil : cldrCurrency
  let currencyArg = currency.map { dartString($0) } ?? "null"
  out += "  IsoCountry(\(dartString(code)), \(dartString(nameEn)), \(dartString(nameAr)), \(currencyArg)),\n"
}
out += "];\n"
print(out, terminator: "")

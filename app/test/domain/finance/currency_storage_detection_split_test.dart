// Closure round, decision 3.7: stored money holds every ISO-4217 currency
// (`kCurrencyScale`, generated by tool/generate_currency_scale.py), while the
// codes recognised in message text (`kDetectionCurrencyScale`) stay exactly
// the 50 they were. Synthetic data only.

class _Keys implements DatabaseKeyStore {
  _Keys(this.key);
  final String key;
  @override
  Future<String> readOrCreateKey() async => key;
  @override
  Future<String?> readStoredKey() async => key;
}

// The detection set and the evidence ISO regex as they were before the split,
// byte for byte.
const _detectionCodes =
    'AED|BDT|BHD|CLP|DJF|DZD|EGP|ETB|EUR|GBP|GHS|GNF|IDR|ILS|INR|IQD|ISK|JOD|'
    'JPY|KES|KMF|KRW|KWD|LBP|LYD|MAD|MRU|MYR|NGN|OMR|PHP|PKR|PYG|QAR|RWF|SAR|'
    'SDG|SGD|SOS|SYP|TND|TRY|TZS|UGX|USD|VND|XAF|XOF|YER|ZAR';

/// A synthetic amount with the currency's full number of decimals.
String _amountFor(String currency, int i) {
  final scale = currencyScale(currency);
  return scale == 0 ? '${1000 + i}' : '${1000 + i}.${'7' * scale}';
}

void main() {
  group('detection set is unchanged', () {
    test('the evidence ISO regex is byte-identical to the pre-split build', () {
      expect(isoLiteralPatternSource,
          '(?<![A-Za-z])($_detectionCodes)(?![A-Za-z])');
      expect((kDetectionCurrencyScale.keys.toList()..sort()).join('|'),
          _detectionCodes);
    });

    test('every detection code is storable with the same scale', () {
      for (final e in kDetectionCurrencyScale.entries) {
        expect(kCurrencyScale[e.key], e.value, reason: e.key);
      }
    });

    test('storable ISO codes that are ordinary words are not read as money',
        () {
      for (final word in ['ALL', 'TOP', 'CUP', 'PEN', 'CAD', 'NOK']) {
        expect(isSupportedCurrency(word), isTrue, reason: word);
        final ev = extractEvidence('Paid $word 25.00 at SHOP');
        expect(ev.items.where((e) => e.evidenceClass == EvidenceClass.currency),
            isEmpty,
            reason: word);
      }
      final sar = extractEvidence('Paid SAR 25.00 at SHOP');
      expect(
          sar.items
              .where((e) => e.evidenceClass == EvidenceClass.currency)
              .map((e) => e.iso),
          ['SAR']);
    });
  });

  group('storage table', () {
    test('is ISO-4217 List One: 155 codes, scales 0/2/3, funds excluded', () {
      expect(kCurrencyScale, hasLength(155));
      const three = ['BHD', 'IQD', 'JOD', 'KWD', 'LYD', 'OMR', 'TND'];
      expect(
          kCurrencyScale.entries
              .where((e) => e.value == 3)
              .map((e) => e.key)
              .toList()
            ..sort(),
          three);
      for (final c in ['JPY', 'KRW', 'BIF', 'VUV', 'XPF', 'CLP', 'ISK']) {
        expect(currencyScale(c), 0, reason: c);
      }
      for (final c in ['CAD', 'CNY', 'NOK', 'BRL', 'CHF', 'MXN', 'AUD']) {
        expect(currencyScale(c), 2, reason: c);
      }
      // Funds, units of account, metals and testing codes stay unsupported.
      for (final c in [
        'CLF',
        'UYW',
        'BOV',
        'CHE',
        'USN',
        'XDR',
        'XAU',
        'XXX',
        'XTS'
      ]) {
        expect(isSupportedCurrency(c), isFalse, reason: c);
      }
    });

    test('amounts format with the currency\'s own decimals', () {
      expect(formatMoneyAmount(1234.5, 'BIF'), '1,235');
      expect(formatMoneyAmount(1234.5, 'XPF'), '1,235');
      expect(formatMoneyAmount(1234.5, 'KWD'), '1,234.500');
      expect(formatMoneyAmount(1234.5, 'CAD'), '1,234.50');
      expect(formatMoneyAmount(1234.5, 'JPY'), '1,235');
    });
  });

  test('every country default currency round-trips through the sync wire', () {
    for (final country in isoCountries) {
      final currency = defaultCurrencyFor(country.code);
      if (country.code == 'AQ') {
        expect(currency, isNull);
        continue;
      }
      expect(currency, isNotNull, reason: country.code);
      final money = Money.parse(_amountFor(currency!, 1), currency);
      final wire = jsonDecode(jsonEncode({
        'amount': moneyToNumericText(money),
        'currency': currency,
      })) as Map<String, dynamic>;
      expect(moneyFromPulledValue(wire['amount'], wire['currency'] as String),
          money,
          reason: country.code);
      // The server returns numeric::text trimmed of trailing zeros.
      final trimmed = (wire['amount'] as String).contains('.')
          ? (wire['amount'] as String).replaceFirst(RegExp(r'\.?0+$'), '')
          : wire['amount'] as String;
      expect(moneyFromPulledValue(trimmed, currency), money,
          reason: country.code);
      // Legacy JSON-number push shape: exact for these magnitudes.
      expect(Money.parse('${moneyToLegacyJsonNumber(money)}', currency), money,
          reason: country.code);
    }
  });

  test('every country default currency is stored and survives backup/restore',
      () async {
    FlutterSecureStorage.setMockInitialValues({});
    final source = await AppDatabase.open(
        executor: NativeDatabase.memory(), keyStore: _Keys('split-a'));
    addTearDown(source.close);
    final accounts = DriftAccountRepository(source);
    final save = SaveManualTransactionUseCase(
        transactionRepository: DriftTransactionRepository(source),
        accountRepository: accounts);
    final now = DateTime.utc(2026, 11, 18, 12);
    final expected = <String, Money>{};
    var i = 0;
    for (final country in isoCountries) {
      final currency = defaultCurrencyFor(country.code);
      if (currency == null) continue;
      final account = await accounts.create(AccountEntity(
        id: 'acct-${country.code}',
        name: 'Synthetic ${country.code}',
        currency: currency,
        type: AccountType.bank,
        isDefault: i == 0,
        sortOrder: i,
        createdAt: now,
        updatedAt: now,
      ));
      final money = Money.parse(_amountFor(currency, i), currency);
      final saved = await save(
        amount: money,
        currency: currency,
        type: TransactionTypeEntity.payment,
        occurredAt: now.subtract(Duration(minutes: i)),
        categoryKey: 'other',
        merchant: 'Synthetic merchant ${country.code}',
        accountId: account.id,
      );
      expected[saved.id] = money;
      i++;
    }
    expect(expected, hasLength(248));

    final snapshot =
        jsonDecode(jsonEncode(await BackupSnapshotBuilder(source).build()))
            as Map<String, dynamic>;
    final target = await AppDatabase.open(
        executor: NativeDatabase.memory(), keyStore: _Keys('split-b'));
    addTearDown(target.close);
    await RestoreBackupUseCase(target)(snapshot);

    final restored = {
      for (final t in await DriftTransactionRepository(target).getAll())
        t.id: t,
    };
    for (final entry in expected.entries) {
      final t = restored[entry.key];
      expect(t, isNotNull, reason: entry.key);
      expect(t!.amountMoney, entry.value, reason: entry.value.currency);
      expect(t.currency, entry.value.currency);
    }
  });
}

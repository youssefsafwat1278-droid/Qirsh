package com.youssefsafwat.mali

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyPermanentlyInvalidatedException
import android.security.keystore.KeyProperties
import android.util.Base64
import java.security.KeyStore
import javax.crypto.AEADBadTagException
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Where the capture queue's AES-256-GCM key lives. Production: [CaptureQueueKey]
 * (Android Keystore). A JVM test substitutes an in-memory key and simulates
 * loss, invalidation and an unanswering store.
 */
internal interface CaptureQueueKeySource {
    /** The key; null only when the store ANSWERED and holds none. Throws when it cannot answer. */
    fun load(): SecretKey?

    /** Creates the key. The queue calls it only when no sealed capture data exists. */
    fun create(): SecretKey

    /** Deletes the key. The queue calls it only once no sealed capture data is left. */
    fun delete()
}

/**
 * The queue key cannot be used. [lost] is a definitive answer (the store holds
 * no key, the key is permanently invalidated, or it is not the key the data was
 * sealed with); otherwise the store did not answer and a retry may succeed.
 */
internal class CaptureKeyException(val lost: Boolean) : Exception("capture queue key unavailable")

/**
 * The key that seals the capture queue at rest: a non-exportable Android
 * Keystore AES-256 key, GCM only, separate from the owner-HMAC key
 * ([CaptureOwnerKey]). No user authentication and no unlocked-device
 * requirement: bank SMS arrive, and must be stored, while the phone is locked.
 * Keystore keys are never part of a backup or a device transfer.
 */
internal object CaptureQueueKey : CaptureQueueKeySource {
    private const val KEYSTORE = "AndroidKeyStore"
    private const val ALIAS = "qirsh_capture_queue_aes_v1"

    private fun store(): KeyStore = KeyStore.getInstance(KEYSTORE).apply { load(null) }

    @Synchronized
    override fun load(): SecretKey? {
        val store = store()
        if (!store.containsAlias(ALIAS)) return null
        return store.getKey(ALIAS, null) as? SecretKey
            ?: throw IllegalStateException("queue key entry unusable")
    }

    @Synchronized
    override fun create(): SecretKey = KeyGenerator
        .getInstance(KeyProperties.KEY_ALGORITHM_AES, KEYSTORE)
        .apply {
            init(
                KeyGenParameterSpec.Builder(
                    ALIAS,
                    KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
                )
                    .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                    .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                    .setKeySize(256)
                    .setRandomizedEncryptionRequired(true)
                    .build(),
            )
        }
        .generateKey()

    @Synchronized
    override fun delete() {
        store().deleteEntry(ALIAS)
    }
}

/**
 * AES-256-GCM envelopes for the capture queue: `qcs1.` + base64(nonce ‖
 * ciphertext ‖ 128-bit tag). The 96-bit nonce is random per seal (generated by
 * the cipher: the Keystore key requires randomized encryption), and the AAD
 * binds each record to its slot and format version, so a record moved to
 * another slot fails authentication.
 */
internal object CaptureSealer {
    private const val TRANSFORM = "AES/GCM/NoPadding"
    private const val PREFIX = "qcs1."
    private const val NONCE_BYTES = 12
    private const val TAG_BITS = 128

    fun seal(key: SecretKey, plain: ByteArray, aad: String): String {
        val cipher = Cipher.getInstance(TRANSFORM)
        try {
            cipher.init(Cipher.ENCRYPT_MODE, key)
        } catch (e: Exception) {
            throw keyFault(e)
        }
        val nonce = cipher.iv
        check(nonce != null && nonce.size == NONCE_BYTES) { "unexpected nonce" }
        cipher.updateAAD(aad.toByteArray(Charsets.UTF_8))
        val sealed = cipher.doFinal(plain)
        return PREFIX + Base64.encodeToString(nonce + sealed, Base64.NO_WRAP)
    }

    /**
     * The plaintext, or null when the envelope is malformed or fails
     * authentication (damaged or tampered). Throws [CaptureKeyException] when
     * the key itself cannot be used: that is never reported as damage.
     */
    fun open(key: SecretKey, envelope: String, aad: String): ByteArray? {
        if (!envelope.startsWith(PREFIX)) return null
        val bytes = try {
            Base64.decode(envelope.substring(PREFIX.length), Base64.NO_WRAP)
        } catch (_: IllegalArgumentException) {
            return null
        }
        if (bytes.size < NONCE_BYTES + TAG_BITS / 8) return null
        val cipher = Cipher.getInstance(TRANSFORM)
        try {
            cipher.init(Cipher.DECRYPT_MODE, key, GCMParameterSpec(TAG_BITS, bytes, 0, NONCE_BYTES))
        } catch (e: Exception) {
            throw keyFault(e)
        }
        cipher.updateAAD(aad.toByteArray(Charsets.UTF_8))
        return try {
            cipher.doFinal(bytes, NONCE_BYTES, bytes.size - NONCE_BYTES)
        } catch (_: AEADBadTagException) {
            null
        } catch (_: Exception) {
            throw CaptureKeyException(lost = false)
        }
    }

    /** Only a permanently invalidated key is a definitive loss at init. */
    private fun keyFault(e: Exception): CaptureKeyException {
        var cause: Throwable? = e
        while (cause != null) {
            if (cause is KeyPermanentlyInvalidatedException) return CaptureKeyException(lost = true)
            cause = cause.cause
        }
        return CaptureKeyException(lost = false)
    }
}

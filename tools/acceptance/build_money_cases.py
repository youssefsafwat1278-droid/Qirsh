def forged(text, amount, currency):
    """A 'completed' model answer consistent with a figure in the text."""
    lit = None
    for m in FIGURE.finditer(text):
        code = m.group(1) or m.group(4) or dict(CUR_WORDS).get(m.group(5) or '', None)
        num = m.group(2) or m.group(3)
        val = float(num.replace(',', ''))
        if amount is None or abs(val - amount) < 0.005:
            lit, currency = num, (currency or ('SAR' if code == 'SR' else code) or 'SAR')
            amount = val
            break
    if lit is None:
        if amount is None:
            m = re.search(r'(?<![*0-9])([0-9][0-9,]*(?:\.[0-9]+)?)', text)
            if not m:
                return None
            lit, amount = m.group(1), float(m.group(1).replace(',', ''))
        else:
            lit = f'{amount:.2f}'
        currency = currency or 'SAR'
    credit = bool(CREDITISH.search(text))
    return {'amount': amount, 'amount_text': lit.replace(',', ''), 'currency': currency,
            'type': 'refund' if credit else 'payment', 'direction': 'credit' if credit else 'debit'}


def expected(truth, amount, currency):
    if truth in ('d', 'c', 't'):
        e = {'outcome': 'recorded', 'class': {'d': 'debit', 'c': 'credit', 't': 'transfer'}[truth]}
        if amount is not None:
            e['amount'] = amount
        if currency is not None:
            e['currency'] = currency
        return e
    return {'outcome': 'ignored' if truth == 'i' else 'review'}


rows, seen = [], {}


def add(rid, truth, amount, currency, source, text, alt=None):
    if rid in TABLE_RELABEL:
        (truth, amount, currency), source = TABLE_RELABEL[rid], source + ' (relabelled round 5)'
    if text in seen:
        seen[text]['also'].append(source)
        return
    e = expected(truth, amount, currency)
    f = forged(text, amount, currency) if truth in ('n', 'r', 'i', 'd', 'c', 't') else None
    # Mode (c) tests a false "completed", not a wrong direction: on a
    # completed row the forged answer keeps the true direction.
    if f and truth in ('d', 't'):
        f.update(type='payment', direction='debit')
    if f and truth == 'c':
        f.update(type='refund' if f['type'] == 'refund' else 'income', direction='credit')
    r = {'id': rid, 'text': text, 'sender': 'SNB', 'source': source, 'truth': truth, 'also': []}
    if amount is not None:
        r['amount'] = amount
    if currency is not None:
        r['currency'] = currency
    r['forged'] = f
    if alt:
        e = {**e, 'alt': alt}
    r['expected'] = {'ai_off': e, 'ai_correct': e, 'ai_wrong_completed': e}
    # ai_flipped: the model answers the true figure in the other direction
    # (a completed debit/credit only).
    if truth in ('d', 'c') and f:
        r['expected']['ai_flipped'] = e
    seen[text] = r
    rows.append(r)


